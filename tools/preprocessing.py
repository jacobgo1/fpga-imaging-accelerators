"""The preprocessing every model shares, in numpy only: keep raw bands 8-117 and z-score them
with training's mean and std (hypso-onboard-segmentation: mu_sd.txt).

read_preprocessing  (kept bands, mean, 1/std) from mu_sd.txt
preprocess          the float z-score: what the golden kernels' notebooks do on the ARM
prep_constants      the same as integers, (dn * A + B) >> prep_frac, as the optimized
                    kernels do it in hardware
preprocess_fixed    that integer z-score, bit for bit

The 2D kernels (justounetsimple_opt, waveletcnn_opt, sp_unet_*_opt) take it as int8 with
IN_FRAC fraction bits; `python tools/preprocessing.py` writes their constants into
src/optimized/shared/zscore_int8.hpp. The 1D kernels use a 12-bit format of their own
(tools/justoliunet_model.py), from the same prep_constants.
"""
from pathlib import Path
import re

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
MU_SD = ROOT / 'mu_sd.txt'
RAW_BANDS = 120
DROPPED_BANDS = [0, 1, 2, 3, 4, 5, 6, 7, 118, 119]
FIRST_BAND = 8
# The 2D kernels' input: x * 2^IN_FRAC as int8, saturated at +-IN_MAX (z-scores -3.97 .. 3.97;
# never -128, so two products can share a DSP, see src/optimized/shared/conv3x3_packed.hpp).
# On the aegean capture, int8 input changes 0.04% of justounetsimple's classes (against the
# float model) and leaves its accuracy against the labels the same (96.20%).
IN_FRAC, IN_MAX, PREP_FRAC = 5, 127, 22
HEADER = ROOT / 'src/optimized/shared/zscore_int8.hpp'


def _mu_sd(mu_sd):
    arrays = re.findall(r'\[([^\]]*)\]', Path(mu_sd).read_text())
    if len(arrays) != 2:
        raise ValueError(f'{mu_sd}: expected a mu array and an sd array')
    return [np.array([float(v) for v in a.replace(',', ' ').split()]) for a in arrays]


def read_preprocessing(mu_sd=MU_SD):
    """(kept band indices, per-band mean, per-band 1/std) from the training mu_sd.txt."""
    mean, std = _mu_sd(mu_sd)
    kept = np.array([b for b in range(RAW_BANDS) if b not in DROPPED_BANDS])
    if len(mean) != len(kept) or len(std) != len(kept):
        raise ValueError(f'{mu_sd} has {len(mean)} means and {len(std)} stds; {len(kept)} bands are kept')
    return kept, mean.astype(np.float32), (1.0 / std).astype(np.float32)


def preprocess(raw, kept, mean, inv_std):
    """(x - mean) * (1/std) on the kept bands, in float32. raw: (..., 120)."""
    return (np.asarray(raw, dtype=np.float32)[..., kept] - mean) * inv_std


def quantize_input(x):
    """Preprocessed values (float) -> int8 with IN_FRAC fraction bits, rounded, saturated."""
    return np.clip(np.rint(np.asarray(x, dtype=np.float32) * np.float32(2.0 ** IN_FRAC)),
                   -IN_MAX, IN_MAX).astype(np.int8)


def prep_constants(mu_sd=MU_SD, in_frac=IN_FRAC, prep_frac=PREP_FRAC):
    """The z-score as integers: (A, B), 112 int64 each, for kept band k (raw band 8 + k):
    round((dn - mean) / std * 2^in_frac) = (dn * A[k] + B[k]) >> prep_frac, within one unit.
    The kept bands must be one contiguous run, raw bands 8-117: then a pixel's 120 raw bands
    are 15 words of 8, words 1-14 are kept bands 0-111, and 110 and 111 (raw 118 and 119)
    get A = B = 0."""
    kept, _, _ = read_preprocessing(mu_sd)
    if list(kept) != list(range(FIRST_BAND, 118)):
        raise ValueError('the optimized kernels expect the kept bands to be raw bands 8-117')
    mean, std = _mu_sd(mu_sd)
    scale = 2.0 ** (in_frac + prep_frac) / std
    a = np.zeros(112, dtype=np.int64)
    b = np.zeros(112, dtype=np.int64)
    a[:110] = np.rint(scale)
    b[:110] = np.rint(-mean * scale) + (1 << (prep_frac - 1))     # + half: rounds to nearest
    return a, b


def preprocess_fixed(raw, prep=None, prep_frac=PREP_FRAC, in_max=IN_MAX, dtype=np.int8):
    """Raw L1a values (..., 120, integers) -> the kernel's integer input (..., 110)."""
    a, b = prep if prep is not None else prep_constants(prep_frac=prep_frac)
    dn = np.asarray(raw).astype(np.int64)[..., FIRST_BAND:118]
    return np.clip((dn * a[:110] + b[:110]) >> prep_frac, -in_max, in_max).astype(dtype)


def header(mu_sd=MU_SD):
    """The text of zscore_int8.hpp."""
    a, b = prep_constants(mu_sd)
    _, mean, inv_std = read_preprocessing(mu_sd)

    def rows(items):
        items = list(items)
        return ',\n'.join('    ' + ', '.join(items[i:i + 8]) for i in range(0, len(items), 8))

    a_rows, b_rows = rows(str(v) for v in a), rows(str(v) for v in b)
    mean_rows = rows(f'{float(v)!r}f' for v in mean)
    inv_std_rows = rows(f'{float(v)!r}f' for v in inv_std)
    return f"""// Generated by tools/preprocessing.py from mu_sd.txt -- do not edit; run
//     python tools/preprocessing.py
// after changing mu_sd.txt or the format there.
//
// The 2D kernels' preprocessing in integers. Kept band k is raw band 8 + k (bands
// 0-7 and 118-119 are dropped); 110 and 111 are raw bands 118 and 119, zeroed by A = B = 0:
//     x * 2^IN_FRAC = round((dn - mean) / std * 2^IN_FRAC) = (dn * A[k] + B[k]) >> FRAC
// (to within one unit), saturated to +-IN_MAX (int8, never -128).
#ifndef ZSCORE_INT8_HPP
#define ZSCORE_INT8_HPP

#include <stdint.h>

namespace zscore_int8 {{
constexpr int IN_FRAC = {IN_FRAC};
constexpr int IN_MAX = {IN_MAX};
constexpr int FRAC = {PREP_FRAC};
constexpr int FIRST_BAND = {FIRST_BAND};

static const int32_t A[112] = {{
{a_rows}
}};
static const int32_t B[112] = {{
{b_rows}
}};

// The float preprocessing these approximate (testbench reference): (dn - MEAN) * INV_STD.
static const float MEAN[110] = {{
{mean_rows}
}};
static const float INV_STD[110] = {{
{inv_std_rows}
}};
}}  // namespace zscore_int8

#endif // ZSCORE_INT8_HPP
"""


if __name__ == '__main__':
    HEADER.write_text(header(), encoding='utf-8', newline='\n')
    print(f'wrote {HEADER.relative_to(ROOT)}')
